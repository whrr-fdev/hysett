#include "AnimsManager.h"
#include <QProcess>
#include <QDir>
#include <QFile>
#include <QTextStream>
#include <QRegularExpression>

AnimsManager::AnimsManager(QObject *parent) : QObject(parent) {
    initDefaults();
    m_anims = m_defaults;
    loadFromLua();
}

void AnimsManager::initDefaults() {
    auto add = [this](const QString &leaf, const QString &title, bool en, qreal sp, const QString &kind, const QString &curve, const QString &style = "") {
        QVariantMap m;
        m["leaf"] = leaf;
        m["title"] = title;
        m["enabled"] = en;
        m["speed"] = sp;
        m["curve_kind"] = kind;
        m["curve_name"] = curve;
        m["style"] = style;
        m_defaults.append(m);
    };

    add("global", "Глобальная скорость", true, 10.0, "bezier", "default");
    add("border", "Рамки окон", true, 5.39, "bezier", "easeOutQuint");
    add("windows", "Окна (перемещение)", true, 4.79, "spring", "easy");
    add("windowsIn", "Появление окон", true, 4.10, "spring", "easy", "popin 87%");
    add("windowsOut", "Закрытие окон", true, 1.49, "bezier", "linear", "popin 87%");
    add("fadeIn", "Появление окон (Fade)", true, 1.73, "bezier", "almostLinear");
    add("fadeOut", "Исчезновение окон (Fade)", true, 1.46, "bezier", "almostLinear");
    add("fade", "Общий фейд", true, 3.03, "bezier", "quick");
    add("layers", "Слои интерфейса", true, 3.81, "bezier", "easeOutQuint");
    add("layersIn", "Появление слоев", true, 4.00, "bezier", "easeOutQuint", "fade");
    add("layersOut", "Исчезновение слоев", true, 1.50, "bezier", "linear", "fade");
    add("fadeLayersIn", "Плавное появление слоев", true, 1.79, "bezier", "almostLinear");
    add("fadeLayersOut", "Плавное скрытие слоев", true, 1.39, "bezier", "almostLinear");
    add("workspaces", "Рабочие столы", true, 7.00, "bezier", "easeOutQuint", "slide");
    add("workspacesIn", "Вход на рабочий стол", true, 7.00, "bezier", "easeOutQuint", "slide");
    add("workspacesOut", "Выход с рабочего стола", true, 7.00, "bezier", "easeOutQuint", "slide");
    add("zoomFactor", "Масштабирование (Zoom)", true, 7.00, "bezier", "quick");
}

void AnimsManager::loadFromLua() {
    QString luaPath = QDir::homePath() + "/.config/hypr/anims.lua";
    QFile file(luaPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) return;

    QString content = QString::fromUtf8(file.readAll());
    for (int i = 0; i < m_anims.size(); ++i) {
        QVariantMap m = m_anims[i].toMap();
        QString leaf = m["leaf"].toString();
        // hl.animation({ leaf = "border", enabled = true, speed = 5.39, bezier = "easeOutQuint" })
        QRegularExpression re(QString("leaf\\s*=\\s*\"%1\"[^\n]*enabled\\s*=\\s*(true|false)[^\n]*speed\\s*=\\s*([0-9.]+)[^\n]*(bezier|spring)\\s*=\\s*\"([^\"]+)\"").arg(leaf));
        auto match = re.match(content);
        if (match.hasMatch()) {
            m["enabled"] = (match.captured(1) == "true");
            m["speed"] = match.captured(2).toDouble();
            m["curve_kind"] = match.captured(3);
            m["curve_name"] = match.captured(4);
            m_anims[i] = m;
        }
    }
}

void AnimsManager::pushBackup() {
    m_history.append(m_anims);
    if (m_history.size() > 20) m_history.removeFirst();
    emit backupCountChanged();
}

void AnimsManager::applyKeyword(int index) {
    if (index < 0 || index >= m_anims.size()) return;
    QVariantMap m = m_anims[index].toMap();
    QString leaf = m["leaf"].toString();
    QString en = m["enabled"].toBool() ? "1" : "0";
    QString sp = QString::number(m["speed"].toDouble(), 'f', 2);
    QString curve = m["curve_name"].toString();
    QString style = m["style"].toString();

    QString val = QString("%1,%2,%3,%4").arg(leaf, en, sp, curve);
    if (!style.isEmpty()) val += "," + style;
    QProcess::startDetached("hyprctl", {"keyword", "animation", val});
}

void AnimsManager::applyAndSave() {
    QString luaPath = QDir::homePath() + "/.config/hypr/anims.lua";
    QFile file(luaPath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) return;

    QTextStream out(&file);
    out << "-- Auto-generated by Control Center\n";
    for (const auto &item : m_anims) {
        QVariantMap m = item.toMap();
        QString styleStr = m["style"].toString().isEmpty() ? "" : QString(", style = \"%1\"").arg(m["style"].toString());
        out << QString("hl.animation({ leaf = \"%1\", enabled = %2, speed = %3, %4 = \"%5\"%6 })\n")
            .arg(m["leaf"].toString())
            .arg(m["enabled"].toBool() ? "true" : "false")
            .arg(m["speed"].toDouble(), 0, 'f', 2)
            .arg(m["curve_kind"].toString())
            .arg(m["curve_name"].toString())
            .arg(styleStr);
    }
}

void AnimsManager::setAnimEnabled(int index, bool enabled) {
    if (index < 0 || index >= m_anims.size()) return;
    pushBackup();
    QVariantMap m = m_anims[index].toMap();
    m["enabled"] = enabled;
    m_anims[index] = m;
    applyKeyword(index);
    applyAndSave();
    emit animsChanged();
}

void AnimsManager::setAnimSpeed(int index, qreal speed) {
    if (index < 0 || index >= m_anims.size()) return;
    pushBackup();
    QVariantMap m = m_anims[index].toMap();
    m["speed"] = speed;
    m_anims[index] = m;
    applyKeyword(index);
    applyAndSave();
    emit animsChanged();
}

void AnimsManager::setAnimCurve(int index, const QString &kind, const QString &name) {
    if (index < 0 || index >= m_anims.size()) return;
    pushBackup();
    QVariantMap m = m_anims[index].toMap();
    m["curve_kind"] = kind;
    m["curve_name"] = name;
    m_anims[index] = m;
    applyKeyword(index);
    applyAndSave();
    emit animsChanged();
}

void AnimsManager::resetItem(int index) {
    if (index < 0 || index >= m_anims.size() || index >= m_defaults.size()) return;
    pushBackup();
    m_anims[index] = m_defaults[index];
    applyKeyword(index);
    applyAndSave();
    emit animsChanged();
}

void AnimsManager::undo() {
    if (m_history.isEmpty()) return;
    m_anims = m_history.takeLast();
    for (int i = 0; i < m_anims.size(); ++i) applyKeyword(i);
    applyAndSave();
    emit animsChanged();
    emit backupCountChanged();
}
